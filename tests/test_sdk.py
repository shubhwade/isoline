def test_excel_report_is_honest_for_sparse_data(tmp_path) -> None:
    from unittest.mock import patch

    import openpyxl

    import isoline
    from isoline.core.scanner import IsolineScanner
    from isoline.exporters.excel import ExcelExporter

    fin = {"info": {"symbol": "EMP", "longName": "Sparse Co", "exchange": "X"}}
    with patch("isoline.core.scanner.load_financials", return_value=fin):
        r = IsolineScanner().scan("EMP")
    out = tmp_path / "e.xlsx"
    with patch("isoline.core.loaders.load_financials", return_value=fin):
        ExcelExporter().export(r, str(out))
    wb = openpyxl.load_workbook(out)
    assert wb["Summary"]["A1"].value == f"Generated by isoline v{isoline.__version__}"
    assert [wb["Valuation"].cell(row=i, column=3).value for i in range(2, 6)] == ["n/a"] * 4
    health = {row[0].value: row[2].value for row in wb["Health"].iter_rows(min_row=2) if row[1].value is not None}
    assert set(health.values()) == {"n/a"}
    notes = [c.value for row in wb["Summary"].iter_rows(min_row=14) for c in row if c.value]
    assert any("Altman" in str(n) for n in notes)
    assert "1.81" not in " ".join(str(c.value) for row in wb["Health"].iter_rows() for c in row)


def test_reports_are_self_contained_and_formal(tmp_path) -> None:
    """No JavaScript, no CDN, no web fonts, no remote images: opens identically offline."""
    from unittest.mock import patch

    from isoline.core.result import CompareResult
    from isoline.core.scanner import IsolineScanner
    from isoline.exporters.html_dashboard import HtmlDashboardExporter

    with patch("isoline.core.scanner.load_financials", side_effect=lambda t: _fin(t, quality_company)):
        a, b = IsolineScanner().scan("AAA"), IsolineScanner().scan("BBB")
    exp = HtmlDashboardExporter()
    pages = {}
    for name, fn in (
        ("scan", lambda p: exp.export_scan(a, p)),
        ("compare", lambda p: exp.export_compare(CompareResult("AAA", "BBB", a, b), p)),
        ("screen", lambda p: exp.export_screen([a, b], p)),
    ):
        path = tmp_path / f"{name}.html"
        fn(str(path))
        pages[name] = path.read_text(encoding="utf-8")
    import re

    for html in pages.values():
        low = html.lower()
        assert "<script" not in low and "@import" not in low and "url(" not in low
        # nothing is loaded from anywhere: no remote src/href, and a CSP that forbids it
        assert not re.search(r"""(src|href)\s*=\s*["']?(https?:)?//""", low)
        assert "content-security-policy" in low and "default-src 'none'" in low
        assert "investment advice" in low and "not a registered" in low and "isoline v" in low
        assert html.count("<h1>") == 1
    assert "Piotroski F-score" in pages["scan"] and "21.4%" in pages["scan"]
    assert "Income statement" in pages["scan"] and "Balance sheet" in pages["scan"]
    assert "Stronger" in pages["compare"] and "AAA" in pages["compare"]


def _multi_year_company() -> dict:
    import pandas as pd

    cols = pd.to_datetime(["2024-03-31", "2023-03-31", "2022-03-31", "2021-03-31"])
    income = pd.DataFrame(
        {
            "Total Revenue": [1200, 1000, 900, 800],
            "Net Income": [150, 120, 100, 80],
            "Operating Income": [200, 160, 135, 100],
        },
        index=cols,
    ).T
    cash = pd.DataFrame(
        {
            "Operating Cash Flow": [180, 140, 110, None],  # 2021 not reported
            "Capital Expenditure": [-60, -50, -40, None],
        },
        index=cols,
    ).T
    return {"income_stmt": income, "cashflow": cash, "balance_sheet": pd.DataFrame(), "info": {"financialCurrency": "USD"}}


def test_history_engine_aligns_by_date_and_keeps_gaps_as_none() -> None:
    from isoline.core.engines.history import HistoryEngine

    h = HistoryEngine().run(_multi_year_company())
    assert h is not None and h.years == ["FY2021", "FY2022", "FY2023", "FY2024"]  # oldest first
    assert h.revenue == [800, 900, 1000, 1200]
    assert h.operating_cash_flow == [None, 110, 140, 180]
    assert h.free_cash_flow == [None, 70, 90, 120]  # CFO - |capex|; gap stays None
    assert h.operating_margin[3] == pytest.approx(200 / 1200)
    assert h.currency == "USD"
    assert HistoryEngine().run({}) is None  # nothing to chart


def test_scan_report_contains_two_svg_charts_and_no_zero_bar_for_gaps(tmp_path) -> None:
    from unittest.mock import patch

    from isoline.core.scanner import IsolineScanner
    from isoline.exporters.html_dashboard import HtmlDashboardExporter

    fin = _multi_year_company()
    fin["info"].update({"symbol": "MY", "longName": "Multi Year Co", "exchange": "X"})
    with patch("isoline.core.scanner.load_financials", return_value=fin):
        r = IsolineScanner().scan("MY")
    assert r.history is not None and r.to_dict()["history"]["years"][-1] == "FY2024"
    out = tmp_path / "r.html"
    HtmlDashboardExporter().export_scan(r, str(out))
    html = out.read_text(encoding="utf-8")
    assert html.count("<svg") == 2 and "Is profit turning into cash?" in html
    assert "FY2021" in html and "<script" not in html.lower()
    assert "Arial" in html and "Georgia" not in html  # plain sans with lining figures, as in filings
    # 4 revenue + 4 net income bars in chart 1 (+ gaps skipped in chart 2: 3 CFO + 3 FCF + 4 NI)
    assert html.count("<rect") >= 8 + 10


