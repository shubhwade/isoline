def test_every_documented_cli_command_exists() -> None:
    """docs/cli.md must not describe commands that do not exist."""
    import pathlib
    import re

    from typer.main import get_command

    from telmus.cli.app import app

    docs = pathlib.Path(__file__).resolve().parent.parent / "docs" / "cli.md"
    documented = set(re.findall(r"^## (\w+)\s*$", docs.read_text(encoding="utf-8"), re.M))
    real = set(get_command(app).commands)  # type: ignore[attr-defined]
    assert documented and documented <= real, documented - real
    assert {"scan", "compare", "screen", "check", "powerbi", "serve", "info"} <= documented


def test_excel_report_is_honest_for_sparse_data(tmp_path) -> None:
    from unittest.mock import patch

    import openpyxl

    import telmus
    from telmus.core.scanner import TelmusScanner
    from telmus.exporters.excel import ExcelExporter

    fin = {"info": {"symbol": "EMP", "longName": "Sparse Co", "exchange": "X"}}
    with patch("telmus.core.scanner.load_financials", return_value=fin):
        r = TelmusScanner().scan("EMP")
    out = tmp_path / "e.xlsx"
    with patch("telmus.core.loaders.load_financials", return_value=fin):
        ExcelExporter().export(r, str(out))
    wb = openpyxl.load_workbook(out)
    assert wb["Summary"]["A1"].value == f"Generated by telmus v{telmus.__version__}"
    assert [wb["Valuation"].cell(row=i, column=3).value for i in range(2, 6)] == ["n/a"] * 4
    health = {row[0].value: row[2].value for row in wb["Health"].iter_rows(min_row=2) if row[1].value is not None}
    assert set(health.values()) == {"n/a"}
    notes = [c.value for row in wb["Summary"].iter_rows(min_row=14) for c in row if c.value]
    assert any("Altman" in str(n) for n in notes)
    assert "1.81" not in " ".join(str(c.value) for row in wb["Health"].iter_rows() for c in row)


def test_reports_are_self_contained_and_formal(tmp_path) -> None:
    """No JavaScript, no CDN, no web fonts, no remote images: opens identically offline."""
    from unittest.mock import patch

    from telmus.core.result import CompareResult
    from telmus.core.scanner import TelmusScanner
    from telmus.exporters.html_dashboard import HtmlDashboardExporter

    with patch("telmus.core.scanner.load_financials", side_effect=lambda t: _fin(t, quality_company)):
        a, b = TelmusScanner().scan("AAA"), TelmusScanner().scan("BBB")
    exp = HtmlDashboardExporter()
    pages = {}
    for name, fn in (
        ("scan", lambda p: exp.export_scan(a, p)),
        ("compare", lambda p: exp.export_compare(CompareResult("AAA", "BBB", a, b), p)),
        ("screen", lambda p: exp.export_screen([a, b], p)),
    ):
        path = tmp_path / f"{name}.html"
        fn(str(path))
        pages[name] = path.read_text(encoding="utf-8")
    for html in pages.values():
        low = html.lower()
        assert "<script" not in low and "http://" not in low and "https://" not in low
        assert "investment advice" in low and "not a registered" in low and "telmus v" in low
        assert html.count("<h1>") == 1
    assert "Piotroski F-score signals" in pages["scan"] and "21.4%" in pages["scan"]
    assert "Stronger" in pages["compare"] and "AAA" in pages["compare"]
