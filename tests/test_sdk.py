"""The documented public API must import and work (offline)."""

from __future__ import annotations

from unittest.mock import patch

import pandas as pd
import pytest

from tests.test_scores import company, quality_company


def _fin(symbol: str, base=company) -> dict:
    fin = base()
    fin["info"] = {"symbol": symbol, "longName": symbol + " Inc", "exchange": "X", "marketCap": 3000.0}
    return fin


def test_top_level_imports_are_lazy_and_work() -> None:
    import telmus

    assert telmus.scan is telmus.sdk.scan if hasattr(telmus, "sdk") else callable(telmus.scan)
    from telmus import CompareResult, ScanResult, TelmusScanner, compare, scan  # noqa: F401

    with pytest.raises(AttributeError):
        telmus.does_not_exist  # noqa: B018


def test_scan_compare_and_dataframe() -> None:
    from telmus import compare, scan
    from telmus.sdk import compare_to_dataframe

    with patch("telmus.core.scanner.load_financials", side_effect=lambda t: _fin(t)):
        r = scan("AAA")
        c = compare("AAA", "BBB")
    assert r.ticker == "AAA" and r.health.piotroski_f == 8
    assert (c.ticker_a, c.ticker_b) == ("AAA", "BBB")
    df = compare_to_dataframe(c)
    assert isinstance(df, pd.DataFrame) and list(df.columns) == ["AAA", "BBB"]
    assert df.loc["Piotroski F-score", "AAA"] == 8


def test_json_round_trip_includes_quality_and_notes() -> None:
    import json

    from telmus import scan

    with patch("telmus.core.scanner.load_financials", side_effect=lambda t: _fin(t, quality_company)):
        data = json.loads(scan("Q").to_json())
    assert data["schema_version"] == 1 and "quality" in data and "notes" in data


